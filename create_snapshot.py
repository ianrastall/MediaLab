"""
create_snapshot.py
==================
Generates SNAPSHOT.md — a single Markdown file containing every source file in
the MediaLab solution, suitable for pasting as an AI prompt alongside EXPLAINER.md.

Includes:  .cs  .xaml  .csproj  .slnx  .props  .py  .ps1
           Selected .md files: EXPLAINER.md, HANDOFF.md, WHISPERX_AUDIT.md

Excludes:
  - Directories: bin, obj, Build, .vs, .git, __pycache__, TestResults, .vscode
  - Binary/asset files: *.png, *.ico, *.zip, *.exe, *.dll, etc.
  - Generated C# files: *.g.cs, *.AssemblyInfo.cs, *.GlobalUsings.g.cs
  - This script and other utility scripts
  - Files over 512 KB

Run from the solution root:
    python create_snapshot.py
Output: SNAPSHOT.md
"""

import os
import sys
from pathlib import Path

ROOT = Path(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = ROOT / "SNAPSHOT.md"

# ── Directories to skip entirely ──────────────────────────────────────────────
SKIP_DIRS = {
    "bin", "obj", "Build", ".vs", ".git", "__pycache__",
    "TestResults", ".vscode", "node_modules",
}

# ── Extensions to include ────────────────────────────────────────────────────
INCLUDE_EXTENSIONS = {".cs", ".xaml", ".csproj", ".slnx", ".props", ".py", ".ps1"}

# ── Specific .md files to include ────────────────────────────────────────────
INCLUDE_MD_NAMES = {"EXPLAINER.md", "HANDOFF.md", "WHISPERX_AUDIT.md"}

# ── Generated-file suffixes to skip ──────────────────────────────────────────
GENERATED_SUFFIXES = (
    ".g.cs",
    ".AssemblyInfo.cs",
    ".GlobalUsings.g.cs",
    "_wpftmp.AssemblyInfo.cs",
    "_wpftmp.GlobalUsings.g.cs",
)

# ── Exact filenames to skip ───────────────────────────────────────────────────
SKIP_EXACT = {
    "create_snapshot.py",
    "clean_repo.py",
    "fix_namespaces.py",
    "snapshot.md",      # old output name
    "SNAPSHOT.md",
    "AUDIT.md",         # generated audit doc, not source
}

# ── Binary / asset extensions ─────────────────────────────────────────────────
BINARY_EXTENSIONS = {
    ".png", ".jpg", ".jpeg", ".ico", ".bmp", ".gif", ".tiff", ".tif",
    ".zip", ".exe", ".dll", ".pdb", ".nupkg", ".pfx", ".svg", ".webp",
}

MAX_BYTES = 512 * 1024


def want(rel: str, abs_path: Path) -> bool:
    name = abs_path.name
    ext  = abs_path.suffix.lower()

    if ext in BINARY_EXTENSIONS:
        return False
    if name in SKIP_EXACT:
        return False
    if any(name.endswith(s) for s in GENERATED_SUFFIXES):
        return False
    try:
        if abs_path.stat().st_size > MAX_BYTES:
            return False
    except OSError:
        return False
    if ext == ".md":
        return name in INCLUDE_MD_NAMES
    return ext in INCLUDE_EXTENSIONS


LANG_MAP = {
    ".cs":    "csharp",
    ".xaml":  "xml",
    ".csproj":"xml",
    ".slnx":  "xml",
    ".props": "xml",
    ".py":    "python",
    ".ps1":   "powershell",
    ".md":    "markdown",
}


def read_text(path: Path) -> str:
    for enc in ("utf-8", "utf-8-sig", "latin-1"):
        try:
            return path.read_text(encoding=enc)
        except UnicodeDecodeError:
            continue
    return "(unreadable — skipped)"


def collect():
    entries = []
    for dirpath, dirnames, filenames in os.walk(ROOT):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
        for name in sorted(filenames):
            abs_path = Path(dirpath) / name
            rel = abs_path.relative_to(ROOT).as_posix()
            if want(rel, abs_path):
                entries.append((rel, abs_path))
    entries.sort(key=lambda x: x[0].lower())
    return entries


def main():
    files = collect()
    if not files:
        print("No files found. Run from the MediaLab solution root.")
        sys.exit(1)

    print(f"Writing {len(files)} files to {OUTPUT.name} ...")

    with OUTPUT.open("w", encoding="utf-8") as out:
        out.write("# MediaLab — Full Source Snapshot\n\n")
        out.write(
            "Auto-generated by `create_snapshot.py`. Contains every source file "
            "in the solution, excluding build artifacts, generated code, and binary assets. "
            "Read EXPLAINER.md first for architecture context.\n\n"
        )
        out.write(f"**File count:** {len(files)}\n\n---\n\n")

        for rel, abs_path in files:
            lang = LANG_MAP.get(abs_path.suffix.lower(), "")
            content = read_text(abs_path)
            out.write(f"## `{rel}`\n\n```{lang}\n")
            out.write(content)
            if not content.endswith("\n"):
                out.write("\n")
            out.write("```\n\n---\n\n")

    size_kb = OUTPUT.stat().st_size / 1024
    print(f"Done. SNAPSHOT.md is {size_kb:.0f} KB ({len(files)} files).")


if __name__ == "__main__":
    main()
